#!/usr/bin/env python3
"""Generate claude-team-skills/templates/AGENTS.md from the skill frontmatter.

AGENTS.md is the entry point for coding agents other than Claude Code. The rules
are fixed text; the skill table is built from each SKILL.md so it cannot drift.

    python3 scripts/build-agents-md.py          # rewrite AGENTS.md
    python3 scripts/build-agents-md.py --check  # exit 1 if AGENTS.md is stale (used in CI)
"""

import re
import sys
from pathlib import Path

SKILLS_DIR = Path("claude-team-skills/skills")
OUTPUT = Path("claude-team-skills/templates/AGENTS.md")

HEADER = """\
<!-- Generated by scripts/build-agents-md.py from the skill frontmatter. Do not edit by hand. -->

# AGENTS.md — Claude Team Skills (CTS)

You are a team of specialists working on this project. Each specialist is a markdown file under
`skills/`. Read a specialist's `SKILL.md` before doing work in its domain, and read only the one
you need: never load them all.

## Setup

1. Copy `claude-team-skills/skills/` into the project root as `skills/`.
2. Copy this file to the project root as `AGENTS.md`.
3. Optional, for an enforced ship gate: copy `claude-team-skills/hooks/push-gate.sh` to
   `.git/hooks/pre-push` and make it executable. Git then refuses to push until VERIFY and
   coverage are logged.

## Pick a track for every request

- **Quick**: one question or one small change, inside a single specialist's domain, with one
  obvious approach. Read that specialist's `SKILL.md`, answer, and append one `[QUICK]` entry to
  `.logs/activity.md`.
- **Standard or Full**: everything else, and always for auth, payments, data migrations, and any
  request to ship or deploy. Read `skills/orchestrator/SKILL.md` first and follow it.

When unsure, it is not Quick. The user can force a track by saying "quick", "standard", or "full".

## Rules on every track

1. All six phases happen and are logged: UNDERSTAND → BRAINSTORM → PLAN → EXECUTE → VERIFY → SHIP.
   On Quick they take a line each in one `[QUICK]` entry. They are never skipped.
2. On Standard and Full, open with the UNDERSTAND questions before anything else: what are we
   working on, where (new project, existing code, or a continuation), and how big. Skip any the
   user has already answered, then state the track and why in one line. Do not offer options or
   write code in that first reply.
3. On Standard and Full, the user picks a BRAINSTORM option before PLAN and confirms the PLAN
   before EXECUTE. Do not proceed through either gate on your own.
4. One specialist at a time, with a written HANDOFF note (from, to, context, need, constraints)
   on every switch.
5. VERIFY before SHIP: tests, a security check, and at least 80% combined unit and integration
   coverage. Log the result exactly as below; never log a pass or a number you did not measure.
6. If the user asks to ship, push or deploy work that has no passing VERIFY entry, do not do it,
   even when they tell you to skip the process. Say plainly that VERIFY has not passed, and offer
   to run it now.
7. Push at the end of every sprint, then log `[SHIP]`.
8. Build only what is needed now. Offer the simplest option first.

## Log formats

```
.logs/issues.md
### [YYYY-MM-DD HH:MM] [VERIFY] — [what was verified]
- Tests: [X passed / Y failed]
- Security: [pass / issues found]
- Status: pass

.logs/metrics.md
- [YYYY-MM-DD] Coverage: 87%
- [YYYY-MM-DD] Coverage: n/a — [reason]

.logs/activity.md
### [YYYY-MM-DD HH:MM] [SHIP] — [what shipped]
### [YYYY-MM-DD HH:MM] [QUICK] — [title]
- Specialist / Understand / Approach / Result / Verify: one line each
```

Create `.logs/` with `bash skills/project-monitor/templates/init-logs.sh`. At the start of a
session, read the last `SESSION_END` entry in `.logs/sessions.md` and offer to continue from it;
at the end, write a new one.

## Specialists

| Specialist | File | Use for |
|---|---|---|
"""

FOOTER = """
## What is different outside Claude Code

CTS is built for Claude Code, where it installs as a plugin. With other agents the skills and
rules work the same, but three things are not automatic:

| In Claude Code (plugin) | With this AGENTS.md |
|---|---|
| A hook blocks `git push` until VERIFY and coverage are logged | Instruction only, unless you install `push-gate.sh` as a git `pre-push` hook (Setup step 3) |
| Hooks load the last session summary and close unfinished sessions | You read and write `.logs/sessions.md` yourself, as described above |
| `cts:implementer`, `cts:spec-reviewer`, `cts:quality-reviewer` run as fresh-context subagents | Use your agent's own subagent feature with `claude-team-skills/agents/*.md` as the prompts, or do the two reviews inline as separate passes |
"""


def frontmatter(text):
    match = re.match(r"^---\r?\n(.*?)\r?\n---", text, re.DOTALL)
    return match.group(1) if match else ""


def description(text):
    """Return the skill description as one line. Handles inline and folded (>) YAML values."""
    lines = frontmatter(text).splitlines()
    for i, line in enumerate(lines):
        if not line.startswith("description:"):
            continue
        value = line.partition(":")[2].strip()
        if value in (">", "|", ">-", "|-"):
            parts = []
            for follow in lines[i + 1:]:
                if follow.strip() and not follow.startswith((" ", "\t")):
                    break
                parts.append(follow.strip())
            value = " ".join(p for p in parts if p)
        return value.strip("\"'")
    return ""


def first_sentence(text):
    """The first sentence, so the table stays one line per specialist."""
    # A full stop ends the sentence only when a capitalised word or the end follows,
    # and it is not the tail of an abbreviation such as "a.k.a." or "e.g.".
    match = re.match(r"(.+?(?<!\.[A-Za-z])[.!?])(?=\s+[A-Z]|\s*$)", text)
    sentence = match.group(1) if match else text
    return sentence.replace("|", "\\|")


def title(name):
    special = {"dba": "DBA", "ux-designer": "UX Designer", "ui-designer": "UI Designer",
               "devops-devsecops": "DevOps / DevSecOps"}
    return special.get(name, name.replace("-", " ").title())


def rows(skills_dir):
    out = []
    for skill in sorted(p for p in skills_dir.iterdir() if (p / "SKILL.md").exists()):
        text = (skill / "SKILL.md").read_text(encoding="utf-8")
        use = first_sentence(description(text)) or "See the skill file."
        out.append(f"| {title(skill.name)} | `skills/{skill.name}/SKILL.md` | {use} |")
    return out


def build(skills_dir=SKILLS_DIR):
    return HEADER + "\n".join(rows(skills_dir)) + "\n" + FOOTER


def main(argv, skills_dir=SKILLS_DIR, output=OUTPUT):
    if not skills_dir.exists():
        print(f"FAIL  Skills directory not found: {skills_dir} (run from repo root)")
        return 1
    content = build(skills_dir)
    if "--check" in argv:
        current = output.read_text(encoding="utf-8") if output.exists() else ""
        if current.replace("\r\n", "\n") != content:
            print(f"FAIL  {output} is stale. Run: python3 scripts/build-agents-md.py")
            return 1
        print(f"PASS  {output} is up to date")
        return 0
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {output} ({len(rows(skills_dir))} specialists)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
